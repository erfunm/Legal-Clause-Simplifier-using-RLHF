"""Composite reward utilities for PPO-based RLHF training.

The reward function combines multiple objectives that encourage faithful yet
readable simplifications of legal clauses:

* **BERTScore** ensures semantic similarity to the human reference;
* **SARI** rewards rewriting operations that improve simplicity;
* **Flesch–Kincaid Grade Level** provides a readability bonus when the output
  is accessible;
* **Entity preservation** penalises dropping or mutating critical entities such
  as dates, amounts, or party names.

The helpers in this module are designed to be called from PPO training loops
running on SageMaker.  They are lightweight wrappers that keep heavy
dependencies (``bert-score`` and ``easse``) inside the function scope, allowing
importing the module even when those packages are unavailable (e.g. documentation
builds).
"""

from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache
from typing import Dict, Iterable, Mapping, MutableMapping, Optional, Sequence, Tuple

from utils import check_entity_presence, extract_entities, validate_entities


DEFAULT_WEIGHTS: Dict[str, float] = {
    "bertscore": 0.5,
    "sari": 0.3,
    "readability": 0.2,
    "entity_penalty": 1.0,
}

  
@dataclass
class RewardComponents:
    """Breakdown of the individual reward signals."""

    bertscore: float
    sari: float
    readability_bonus: float
    entity_penalty: float

    def weighted_sum(self, weights: Mapping[str, float] | None = None) -> float:
        """Return the weighted reward using ``weights`` or defaults."""

        weights = weights or DEFAULT_WEIGHTS
        return (
            weights["bertscore"] * self.bertscore
            + weights["sari"] * self.sari
            + weights["readability"] * self.readability_bonus
            - weights["entity_penalty"] * self.entity_penalty
        )


def _load_bertscore_resources():  # pragma: no cover - heavy import
    """Import ``bert_score`` lazily to keep module imports cheap."""

    try:
        from bert_score import score  # type: ignore import
    except ImportError as exc:  # pragma: no cover - optional dependency
        raise RuntimeError(
            "bert-score is required to compute the semantic similarity reward. "
            "Install it via `pip install bert-score`."
        ) from exc
    return score


def _load_sari_resources():  # pragma: no cover - heavy import
    """Import ``easse.sari`` lazily to avoid start-up overhead."""

    try:
        from easse.sari import corpus_sari  # type: ignore import
    except ImportError as exc:  # pragma: no cover - optional dependency
        raise RuntimeError(
            "easse is required to compute SARI. Install it via `pip install easse`."
        ) from exc
    return corpus_sari


@lru_cache(maxsize=1)
def _load_textstat():  # pragma: no cover - heavy import
    """Return the ``textstat`` module (cached)."""

    try:
        import textstat  # type: ignore import
    except ImportError as exc:  # pragma: no cover - optional dependency
        raise RuntimeError(
            "textstat is required to compute readability scores. Install it via "
            "`pip install textstat`."
        ) from exc
    return textstat


def compute_bertscore(prediction: str, reference: str, *, lang: str = "en", rescale_with_baseline: bool = True) -> float:
    """Return BERTScore-F1 between ``prediction`` and ``reference``."""

    score_fn = _load_bertscore_resources()
    P, R, F1 = score_fn([prediction], [reference], lang=lang, rescale_with_baseline=rescale_with_baseline)
    return float(F1.item())


def compute_sari(source: str, prediction: str, reference: str) -> float:
    """Return the SARI score for the given triple."""

    corpus_sari = _load_sari_resources()
    # ``corpus_sari`` expects iterables of strings.
    return float(corpus_sari([source], [prediction], [[reference]]))


def compute_readability_bonus(prediction: str, *, target_grade: float = 8.0) -> float:
    """Convert Flesch–Kincaid Grade Level into a normalised bonus.

    The function rewards outputs whose FKGL is below ``target_grade`` (default 8).
    Scores higher than the target receive zero bonus, while very easy text is
    capped at 1.0.  ``prediction`` is expected to be a string generated by the
    model.
    """

    textstat = _load_textstat()
    fkgl = float(textstat.flesch_kincaid_grade(prediction))
    if fkgl <= 0:
        return 1.0
    bonus = max(0.0, (target_grade - fkgl) / target_grade)
    return min(1.0, bonus)


def compute_entity_penalty(entities: Sequence[str], prediction: str, *, clause: Optional[str] = None, missing_penalty: float = 0.5) -> Tuple[float, MutableMapping[str, bool]]:
    """Return the entity penalty and per-entity preservation mapping."""

    if not entities and clause:
        entities = tuple(extract_entities(clause))
    entities = tuple(validate_entities(entities))
    if not entities:
        return 0.0, {}
    presence = check_entity_presence(entities, prediction)
    missing = sum(1 for entity, kept in presence.items() if not kept)
    penalty = missing_penalty * (missing / len(entities)) if entities else 0.0
    return penalty, presence


def compute_reward(
    *,
    clause: str,
    reference: str,
    prediction: str,
    entities: Optional[Sequence[str]] = None,
    weights: Optional[Mapping[str, float]] = None,
    bertscore_lang: str = "en",
    readability_target: float = 8.0,
    missing_entity_penalty: float = 0.5,
) -> Tuple[float, RewardComponents, MutableMapping[str, bool]]:
    """Compute the composite reward and return diagnostic information.

    Parameters
    ----------
    clause:
        The original legal clause.
    reference:
        Human-authored simplified clause.
    prediction:
        Model-generated simplification.
    entities:
        Optional iterable of entities that must be preserved.  When omitted the
        helper re-extracts entities from ``clause`` using ``utils.extract_entities``.
    weights:
        Custom weight mapping for the reward components.  Defaults to
        :data:`DEFAULT_WEIGHTS`.
    bertscore_lang:
        Language code supplied to ``bert-score``.
    readability_target:
        Target FKGL below which readability is rewarded.
    missing_entity_penalty:
        Scaling applied to the fraction of missing entities.
    """

    bertscore = compute_bertscore(prediction, reference, lang=bertscore_lang)
    sari = compute_sari(clause, prediction, reference)
    readability_bonus = compute_readability_bonus(prediction, target_grade=readability_target)
    penalty, presence = compute_entity_penalty(
        entities or (),
        prediction,
        clause=clause,
        missing_penalty=missing_entity_penalty,
    )
    components = RewardComponents(
        bertscore=bertscore,
        sari=sari,
        readability_bonus=readability_bonus,
        entity_penalty=penalty,
    )
    reward = components.weighted_sum(weights)
    return reward, components, presence


__all__ = [
    "DEFAULT_WEIGHTS",
    "RewardComponents",
    "compute_bertscore",
    "compute_entity_penalty",
    "compute_readability_bonus",
    "compute_reward",
    "compute_sari",
]
