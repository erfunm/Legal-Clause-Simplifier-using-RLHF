# --- error analysis --------------------------------------------------------------------------


def test_error_analysis_counts_and_samples_each_type(run_dir: Path) -> None:
    result = error_analysis(run_dir, samples_per_type=2, seed=0)
    # truncate is a verbatim prefix of the clause, so the copy detector flags it too
    assert result["counts"]["verbatim_copy"] == {"copy": 4, "truncate": 4, "sft": 4, "sft-grpo": 4}
    assert result["counts"]["entities_dropped"]["truncate"] > 0
    assert result["counts"]["condition_drop"]["truncate"] >= 1  # truncation cuts "unless ..."
    assert result["rates"]["verbatim_copy"]["copy"] == 1.0
    assert len(result["examples"]["verbatim_copy"]) == 2 and result["judge"] is None
    md = (run_dir / "error_analysis.md").read_text()
    assert "| `verbatim_copy`" in md and "## `condition_drop`" in md


def test_error_analysis_uses_low_judge_scores(run_dir: Path) -> None:
    _, rows = load_run(run_dir)
    write_judgements(run_dir, "proxy", ProxyJudge().judge(build_tasks(rows, seed=0)).rows)
    result = error_analysis(run_dir)
    assert result["judge"] == "proxy"
    assert (
        sum(result["counts"]["judge_meaning_lost"].values())
        + sum(result["counts"]["judge_not_plain"].values())
        > 0
    )


# --- report ---------------------------------------------------------------------------------------


def test_report_writes_the_readme_section_and_figures(run_dir: Path, tmp_path: Path) -> None:
    readme = tmp_path / "README.md"
    readme.write_text(README)
    log = tmp_path / "grpo" / "log_history.json"
    log.parent.mkdir()
    log.write_text(
        json.dumps(
            [
                {
                    "step": s,
                    "loss": 0.1,
                    "rewards/meaning/mean": 0.1 * s,
                    "rewards/format/mean": -0.1,
                }
                for s in (1, 2, 3)
            ]
        )
    )
    result = generate_report(
        run_dir.parent,
        readme=readme,
        figures_dir=tmp_path / "figures",
        training_logs=[log],
        cost_log=None,
    )
    text = readme.read_text()
    assert text.startswith("# Project") and text.endswith(
        "## Other\nkept\n"
    )  # outside the markers kept
    section = text.split(START)[1].split(END)[0]
    assert "pending" not in section and "Generated by `lcs report`" in section
    assert "review status **unreviewed**" in section
    assert "| copy |" in section and "| sft-grpo |" in section
    assert "**1.000**" in section  # copy has the best entity recall, in bold
    assert "[" in section  # CIs shown
    assert {p.name for p in result.figures.values()} == {
        "metric_bars.png",
        "quality_vs_cost.png",
        "grpo_reward_curves.png",
    }
    assert all(p.stat().st_size > 1000 for p in result.figures.values())
    assert (run_dir.parent / "report.md").read_text().startswith("# Results")


def test_report_marks_significant_differences_from_sft(tmp_path: Path) -> None:
    config = eval_config(
        tmp_path,
        systems=[
            {"name": "sft", "kind": "copy"},
            {"name": "sft-grpo", "kind": "truncate", "trained": True},
        ],
    )
    run_dir = run_evaluation(config, scorers=fake_scorers(config))
    metrics = json.loads((run_dir / "metrics.json").read_text())
    comparison = metrics["comparisons"]["sft-grpo"]["golden"]["entity_recall"]
    assert comparison["diff"] < 0
    readme = tmp_path / "README.md"
    readme.write_text(README)
    generate_report(run_dir.parent, readme=readme, figures_dir=tmp_path / "f", cost_log=None)
    section = readme.read_text()
    # 4 clauses is too few for p < 0.05 with a permutation test, so no marker is claimed.
    assert (" ▼ |" in section) == (comparison["p_value"] < 0.05)  # in a cell, not the legend


def test_report_refuses_before_writing_anything(tmp_path: Path) -> None:
    config = eval_config(tmp_path, smoke=True)
    run_evaluation(config, scorers=fake_scorers(config))
    readme = tmp_path / "README.md"
    readme.write_text(README)
    with pytest.raises(UnpublishableResultsError):
        generate_report(tmp_path / "results", readme=readme, figures_dir=tmp_path / "figures")
    assert readme.read_text() == README and not (tmp_path / "figures").exists()


def test_report_counts_claude_cost_from_the_cost_log(tmp_path: Path) -> None:
    from legal_simplifier.eval.items import EvalItem
    from legal_simplifier.eval.report import system_costs
    from legal_simplifier.eval.systems import ClaudeSystem
    from legal_simplifier.llm.batch import request_key

    config = eval_config(
        tmp_path, systems=[{"name": "copy", "kind": "copy"}, {"name": "claude", "kind": "claude"}]
    )
    manifest = {
        "systems": [{"name": "copy", "kind": "copy"}, {"name": "claude", "kind": "claude"}],
        "config": json.loads(config.model_dump_json()),
    }
    rows = [
        {
            "system": "claude",
            "dataset": "golden",
            "id": str(i),
            "category": "c",
            "clause": f"Clause {i}.",
            "reference": "r",
            "reference_source": "claude",
        }
        for i in range(2)
    ]
    claude = ClaudeSystem(config.systems[1], config)
    log = tmp_path / "cost.jsonl"
    log.write_text(
        "".join(
            json.dumps(
                {
                    "custom_id": request_key(
                        claude.request(EvalItem("golden", r["id"], "c", r["clause"], "r", "claude"))
                    ),
                    "cost_usd": 0.002,
                }
            )
            + "\n"
            for r in rows
        )
        + json.dumps({"custom_id": "unrelated-judge-call", "cost_usd": 5.0})
        + "\n"
    )
    costs = system_costs(manifest, rows, log)
    assert costs == {
        "copy": None,
        "claude": pytest.approx(2.0),
    }  # $0.002 per clause -> $2 per 1,000


def test_training_logs_from_trainer_history_or_csv_exports(tmp_path: Path) -> None:
    csv_path = tmp_path / "export.csv"
    csv_path.write_text("step,rewards/meaning/mean,loss\n1,0.2,0.5\n2,0.4,\n")
    assert read_training_log(csv_path) == [
        {"step": 1.0, "rewards/meaning/mean": 0.2, "loss": 0.5},
        {"step": 2.0, "rewards/meaning/mean": 0.4},
    ]
    with pytest.raises(ValueError, match="markers"):
        replace_section("no markers", "x")


def test_metrics_are_rebuilt_when_judgements_arrive(run_dir: Path) -> None:
    _, rows = load_run(run_dir)
    write_judgements(run_dir, "proxy", ProxyJudge().judge(build_tasks(rows, seed=0)).rows)
    metrics = aggregate_run(run_dir)
    assert metrics["judge_backend"] == "proxy"
    assert metrics["systems"]["copy"]["golden"]["judge/meaning_preserved"]["mean"] >= 1


# --- the CI eval gate --------------------------------------------------------------------------------


def test_the_gate_fixture_is_labelled_mock() -> None:
    rows = [json.loads(line) for line in (GATE / "examples.jsonl").read_text().splitlines()]
    assert len(rows) == 20 and {r["reference_source"] for r in rows} == {"mock"}
    assert all(r["note"].startswith("MOCK") for r in rows)
    assert "MOCK DATA, not results" in (GATE / "README.md").read_text()


def test_the_gate_passes_on_the_frozen_fixture() -> None:
    result = run_gate(GATE / "examples.jsonl", GATE / "thresholds.json")
    assert result.passed, result.failures
    baseline = json.loads((GATE / "thresholds.json").read_text())["baseline"]
    assert result.metrics == pytest.approx(baseline, abs=1e-4)  # the fixture has not drifted


def test_the_gate_fails_on_a_deliberately_worse_fixture() -> None:
    result = run_gate(GATE / "examples_worse.jsonl", GATE / "thresholds.json")
    assert not result.passed
    failed = " ".join(result.failures)
    for metric in (
        "entity_recall",
        "detector/condition_drop",
        "judge_proxy/meaning_preserved",
        "judge_proxy/obligations_intact",
    ):
        assert metric in failed


def test_gate_thresholds(tmp_path: Path) -> None:
    rows = [json.loads(line) for line in (GATE / "examples.jsonl").read_text().splitlines()]
    metrics = gate_metrics(rows)
    assert check(metrics, {"entity_recall": {"min": 1.01}}) and not check(
        metrics, {"entity_recall": {"min": 0.5}}
    )
    assert check(metrics, {"nope": {"max": 1}}) == [
        "nope: not computed (unknown metric in thresholds)"
    ]


def test_eval_gate_cli_exit_codes() -> None:
    runner = CliRunner()
    ok = runner.invoke(
        app,
        [
            "eval-gate",
            "--examples",
            str(GATE / "examples.jsonl"),
            "--thresholds",
            str(GATE / "thresholds.json"),
        ],
    )
    assert ok.exit_code == 0 and "Eval gate passed." in ok.output
    bad = runner.invoke(
        app,
        [
            "eval-gate",
            "--examples",
            str(GATE / "examples_worse.jsonl"),
            "--thresholds",
            str(GATE / "thresholds.json"),
        ],
    )
    assert bad.exit_code == 1 and "FAIL entity_recall" in bad.output
